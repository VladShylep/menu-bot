export function guessDepartment(name) {
  // Перемагає найдовший збіг: "томатна паста" -> соуси, а не "паст" (бакалія).
  const n = String(name ?? '').toLowerCase();
  let best = 'Інше';
  let bestLen = 0;
  for (const [dept, stems] of KEYWORDS) {
    for (const s of stems) {
      if (s.length > bestLen && n.includes(s)) {
        best = dept;
        bestLen = s.length;
      }
    }
  }
  return best;
}

export function departmentRank(dept) {
  const i = BIEDRONKA_ORDER.indexOf(dept);
  return i === -1 ? BIEDRONKA_ORDER.length : i;
}
